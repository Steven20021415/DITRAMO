def transformer_app(
    S_kVA, Vp, Vs, pf, freq,
    Jpri, Jsec, Tamb, Bmax, material,
    Ucc_percent, R_share,
    profile_unit, load_csv, load_text
):
    try:
        inputs = {
            'S_kVA': float(S_kVA),
            'V_primary_V': float(Vp),
            'V_secondary_V': float(Vs),
            'pf': float(pf),
            'f_Hz': int(freq),
            'J_primary_A_mm2': float(Jpri),
            'J_secondary_A_mm2': float(Jsec),
            'T_ambient_C': float(Tamb),
            'Bmax_T': float(Bmax),
            'material': material,
            'uk_pct': float(Ucc_percent),
            'R_fraction': float(R_share),
        }

        sizing = compute_transformer_sizing(inputs)

        fig = plot_efficiency_vs_load(
            S_kVA=inputs['S_kVA'],
            pf=inputs['pf'],
            P_cu_nom=sizing['P_cu_W'],
            P_fe=sizing['P_fe_W'],
            P_stray=sizing['P_stray_W']
        )

        series_file = parse_load_profile_file(load_csv)
        series_text = parse_load_profile_text(load_text)
        load_series = series_file if series_file is not None and len(series_file) > 0 else \
                      series_text if series_text is not None and len(series_text) > 0 else None

        profile_stats = compute_profile_stats(load_series, inputs, sizing, profile_unit) \
                         if load_series is not None else None

        df_report = generate_report(inputs, sizing, profile_stats)

        docx_bytes = df_to_docx(df_report)
        pdf_bytes  = df_to_pdf(df_report)

        docx_path = save_bytes_to_tempfile(docx_bytes, ".docx")
        pdf_path  = save_bytes_to_tempfile(pdf_bytes, ".pdf")

        report_text = df_report.to_string(index=False)

        return report_text, docx_path, pdf_path, fig

    except Exception as e:
        import traceback
        err_msg = f"Erreur : {type(e).__name__}\n{str(e)}\n\n{traceback.format_exc()}"
        return err_msg, None, None, None


