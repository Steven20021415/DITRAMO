# ────────────────────────────────────────────────
# Estimation géométrique du noyau (heuristique)
# ────────────────────────────────────────────────
def estimate_core_section_and_mtl(S_kVA: float) -> tuple[float, float]:
    """
    Estimation empirique de la section nette du noyau et longueur moyenne de spire.

    Hypothèse classique (distribution 50–2000 kVA) :
    S ≈ K × √S_kVA   avec K ≈ 1.1 à 1.3 cm²/√kVA  → ici 1.2 cm²/√kVA
    (valeur souvent rencontrée dans la littérature et chez les fabricants)

    Retour :
        - S_core_net_m² : section nette du noyau [m²]
        - mean_turn_length_m : longueur moyenne d'une spire [m]
    """
    if S_kVA < 1:
        S_kVA = 1.0

    # Coefficient empirique [cm² / √kVA] → conversion en m²
    K = 1.2 / 10_000                  # 1.2 cm² → 1.2 × 10⁻⁴ m²
    S_core_m2 = K * np.sqrt(S_kVA)

    # Dimensions fenêtre ≈ proportionnelles à √S
    window_height_m  = 3.0 * np.sqrt(S_core_m2)
    window_width_m   = 2.0 * np.sqrt(S_core_m2)

    mean_turn_length_m = 2 * (window_height_m + window_width_m)
    mean_turn_length_m = float(np.clip(mean_turn_length_m, 0.55, 1.8))

    return S_core_m2, mean_turn_length_m


# ────────────────────────────────────────────────
# Ajustement densité de courant selon température ambiante
# ────────────────────────────────────────────────
def adjust_current_density(J_target: float, T_ambient_C: float) -> float:
    if T_ambient_C <= 35:
        return J_target

    # Réduction progressive : -1% par °C au-delà de 35 °C, plancher -20%
    factor = np.clip(1.0 - 0.01 * (T_ambient_C - 35), 0.80, 1.00)
    return J_target * factor


# ────────────────────────────────────────────────
# Estimation des élévations de température (approche simplifiée IEC)
# ────────────────────────────────────────────────
def estimate_temperatures(P_fe_W: float, P_cu_W: float, S_kVA: float, cooling="ONAN") -> dict:
    """
    Estimation simplifiée des élévations :
      • Δθ_top-oil   ~ principalement pertes totales
      • Δθ_hot-spot  ~ surtout pertes cuivre + gradient enroulement

    Références typiques ONAN (IEC 60076-2, -7) :
    - Δθ_top-oil ≈ 55–60 K à pleine charge
    - Δθ_hot-spot ≈ 78 K maximum (classe A 105 °C)
    """
    P_total_W = P_fe_W + P_cu_W

    # Base : 50–60 kVA ONAN → ~55 K top-oil pour ~1–1.2 kW pertes totales
    P_ref_W = 1100.0
    exponent_oil = 0.9
    delta_theta_oil = 55.0 * (P_total_W / P_ref_W) ** exponent_oil

    # Gradient enroulement (hot-spot – top oil) plus marqué par pertes cuivre
    gradient_hs = 18.0 * (P_cu_W / (P_cu_W + 0.3 * P_fe_W + 50)) ** 0.8   # pondération indicative

    delta_theta_hs = delta_theta_oil + gradient_hs

    return {
        "top_oil_rise_K": float(np.clip(delta_theta_oil, 25, 70)),
        "hot_spot_rise_K": float(np.clip(delta_theta_hs, 40, 95)),
        "thermal_ok": delta_theta_hs <= 78.0   # limite classe A courante
    }


# ────────────────────────────────────────────────
# Calcul principal du dimensionnement
# ────────────────────────────────────────────────
def compute_transformer_sizing(inputs: dict) -> dict:
    V1     = inputs['V_primary_V']
    V2     = inputs['V_secondary_V']
    S_kVA  = inputs['S_kVA']
    pf     = inputs['pf']
    f      = inputs['f_Hz']
    Bmax   = inputs['Bmax_T']
    T_amb  = inputs['T_ambient_C']
    mat    = get_material_properties(inputs['material'])
    uk_pct = inputs['uk_pct']
    r_frac = inputs['R_fraction']

    # ── Courants nominaux (S apparente) ───────────────
    I1 = S_kVA * 1000 / V1 if V1 > 0 else 0.0
    I2 = S_kVA * 1000 / V2 if V2 > 0 else 0.0

    # ── Noyau ─────────────────────────────────────────
    S_core, Lmt = estimate_core_section_and_mtl(S_kVA)
    B = min(Bmax, mat["B_max_T"])

    N1 = max(1, round(V1 / (4.44 * f * B * S_core)))
    N2 = max(1, round(V2 / (4.44 * f * B * S_core)))

    # ── Conducteurs ───────────────────────────────────
    J1 = adjust_current_density(inputs['J_primary_A_mm2'], T_amb)
    J2 = adjust_current_density(inputs['J_secondary_A_mm2'], T_amb)

    A1 = I1 / J1 if J1 > 0 else 0.0
    A2 = I2 / J2 if J2 > 0 else 0.0

    L1 = N1 * Lmt
    L2 = N2 * Lmt

    # ── Impédance et pertes cuivre ────────────────────
    Z_eq = (uk_pct / 100) * (V1 ** 2) / (S_kVA * 1000)
    R_eq = r_frac * Z_eq
    X_eq = Z_eq - R_eq

    P_cu = I1 ** 2 * R_eq

    # ── Pertes fer + pertes additionnelles ────────────
    M_core = mat["mass_kg_per_kVA"] * S_kVA
    P_fe = mat["specific_loss_W_per_kg"] * M_core
    P_stray = 0.004 * S_kVA * 1000          # ~0.4% typique

    # ── Rendement ─────────────────────────────────────
    P_out = S_kVA * 1000 * pf
    P_total = P_cu + P_fe + P_stray
    eta = 100 * P_out / (P_out + P_total) if P_out > 0 else 0.0

    # ── Températures ──────────────────────────────────
    thermal = estimate_temperatures(P_fe, P_cu, S_kVA)

    return {
        "I1_A": I1, "I2_A": I2,
        "ratio": V1/V2 if V2 else 0,
        "N1": N1, "N2": N2,
        "A1_mm2": A1, "A2_mm2": A2,
        "Lmt_m": Lmt,
        "L1_m": L1, "L2_m": L2,
        "uk_pct": uk_pct,
        "Z_eq_ohm": Z_eq, "R_eq_ohm": R_eq, "X_eq_ohm": X_eq,
        "P_cu_W": P_cu,
        "P_fe_W": P_fe,
        "P_stray_W": P_stray,
        "P_total_W": P_total,
        "efficiency_pct": eta,
        "core_mass_kg": M_core,
        "B_used_T": B,
        **thermal
    }


