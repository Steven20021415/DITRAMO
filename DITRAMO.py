def df_to_docx(df):
    document = Document()
    document.add_heading("Rapport de dimensionnement – DiTraMo", level=1)
    table = document.add_table(rows=1, cols=len(df.columns))
    table.style = 'Light Grid'
    hdr_cells = table.rows[0].cells
    for i, col in enumerate(df.columns):
        hdr_cells[i].text = col
    for _, row in df.iterrows():
        row_cells = table.add_row().cells
        for i, val in enumerate(row):
            row_cells[i].text = str(val)
    bio = BytesIO()
    document.save(bio)
    bio.seek(0)
    return bio.read()

def df_to_pdf(df):

    pdf = FPDF()
    pdf.add_page()

    # cherche automatiquement DejaVu Sans installée via matplotlib
    font_path = font_manager.findfont("DejaVu Sans")

    pdf.add_font(
        "DejaVu",
        "",
        font_path,
        uni=True
    )

    pdf.set_font("DejaVu", size=10)

    pdf.cell(
        0,
        10,
        "Rapport de dimensionnement du transformateur",
        new_x="LMARGIN",
        new_y="NEXT",
        align="C"
    )

    pdf.ln(5)

    col_widths = [90, 60, 30]

    # header
    for i, col in enumerate(df.columns):
        pdf.cell(col_widths[i], 8, str(col), border=1)

    pdf.ln()

    # rows
    for _, row in df.iterrows():

        for i, val in enumerate(row):
            pdf.cell(
                col_widths[i],
                8,
                str(val),
                border=1
            )

        pdf.ln()

    return bytes(pdf.output())

def save_bytes_to_tempfile(content_bytes, suffix=".tmp"):
    fd, path = tempfile.mkstemp(suffix=suffix)
    with os.fdopen(fd, 'wb') as f:
        f.write(content_bytes)
    return path


