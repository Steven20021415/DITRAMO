def compute_profile_stats(load_series, inputs, sizing, profile_unit):
    if load_series is None or len(load_series) == 0:
        return None

    pf = inputs['pf']
    S_kVA = inputs['S_kVA']
    P_fe = sizing['P_fe_W']
    P_cu_nom = sizing['P_cu_W']
    P_stray_nom = sizing['P_stray_W']

    if profile_unit == "kW":
        P_out_W = load_series * 1000.0
        load_factor = P_out_W / (S_kVA * 1000.0 * pf)
    else:  # kVA
        S_out = load_series * 1000.0
        P_out_W = S_out * pf
        load_factor = S_out / (S_kVA * 1000.0)

    load_factor = np.clip(load_factor, 0.0, 1.5)

    P_cu = (load_factor ** 2) * P_cu_nom
    P_stray = (load_factor ** 2) * P_stray_nom
    P_tot = P_cu + P_stray + P_fe

    eta = np.where(P_out_W > 0,
                   100 * P_out_W / (P_out_W + P_tot),
                   0.0)

    return {
        "profile_steps": int(len(load_series)),
        "avg_P_out_W": float(np.mean(P_out_W)),
        "avg_P_cu_W": float(np.mean(P_cu)),
        "avg_P_total_W": float(np.mean(P_tot)),
        "avg_efficiency_pct": float(np.mean(eta)),
        "energy_out_Wh": float(np.sum(P_out_W)),     # supposant pas=1h
        "energy_losses_Wh": float(np.sum(P_tot)),
    }


