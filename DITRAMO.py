# Courbe rendement vs charge
# ────────────────────────────────────────────────
def plot_efficiency_vs_load(S_kVA, pf, P_cu_nom, P_fe, P_stray):
    loads = np.array([0.25, 0.5, 0.75, 1.0, 1.25, 1.5])
    etas = []
    for k in loads:
        P_out = S_kVA * 1000 * pf * k
        P_loss = P_fe + (P_cu_nom + P_stray) * k**2
        eta = 100 * P_out / (P_out + P_loss) if P_out + P_loss > 0 else 0
        etas.append(eta)

    etas = np.array(etas)   # ← conversion ici

    fig, ax = plt.subplots(figsize=(7, 4.5))
    ax.plot(loads * 100, etas, "o-", linewidth=2)
    ax.set_xlabel("Charge (%)")
    ax.set_ylabel("Rendement (%)")
    ax.set_title("Rendement en fonction de la charge")
    ax.grid(True, alpha=0.3)

    ax.set_ylim(bottom=etas.min() - 2, top=etas.max() + 1)   # ← maintenant .min() et .max() marchent
    return fig


