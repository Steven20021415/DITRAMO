def parse_load_profile_file(file_obj):
    if file_obj is None:
        return None
    # Gradio File renvoie un dict avec 'name', 'path', etc. dans les versions récentes
    if hasattr(file_obj, 'name'):
        path = file_obj.name
    else:
        path = file_obj
    try:
        df = pd.read_csv(path)
        if 'P' in df.columns:
            series = df['P']
        elif 'P_kW' in df.columns:
            series = df['P_kW']
        elif 'S_kVA' in df.columns:
            series = df['S_kVA']
        else:
            series = df.iloc[:, 0]
        return pd.to_numeric(series, errors='coerce').dropna()
    except:
        return None


def parse_load_profile_text(text):
    if not text or not str(text).strip():
        return None
    raw = str(text).replace('\n',' ').replace('\t',' ').replace(';',' ')
    parts = [p for p in raw.replace(',', ' ').split(' ') if p.strip()]
    vals = pd.to_numeric(pd.Series(parts), errors='coerce').dropna()
    return vals if len(vals) > 0 else None


